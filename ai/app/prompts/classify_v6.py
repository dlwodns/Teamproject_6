WEEKDAYS = "월화수목금토일"
SIGNATURE = re.compile(r"\n\*{5,}\n(.*?)(?:\n\*{5,}\s*)?$", re.S)  # 사내 메일 서명란: 별표 줄 사이 이름 / 소속 / 연락처


def trim_body(body: str) -> str:
    """서명란을 '보낸사람: 이름 직급 / 소속 끝 칸' 한 줄로 줄인다(입력 토큰 절약). 서명란이 없으면 그대로 둔다."""
    m = SIGNATURE.search(body)
    if not m:
        return body.strip()
    lines = [ln.strip() for ln in m.group(1).strip().split("\n") if ln.strip()]
    who = lines[0].split("/")[0].strip() if lines else ""
    org = lines[1].split("/")[-1].strip() if len(lines) > 1 and not re.match(r"(?:E-?Mail|Phone|Tel|Address)", lines[1], re.I) else ""
    sig = " / ".join(x for x in (who, org) if x)
    return body[:m.start()].strip() + (f"\n(보낸사람: {sig})" if sig else "")


def render_user(req, cond) -> str:
    """메일마다 바뀌는 값. 규칙이 본 조건(수신 방식 · 사내외 · 자동 발송)은 사실로만 넘기고 해석은 모델이 한다."""
    lists = {"role": f"내 직책({req.owner.position or '직책'}) 배포 목록 (나에게 온 지시)", "team": "우리 팀 배포 목록 (나에게 온 지시)",
             "all": "전사·단체 배포 목록"}
    who = {"to": "나", "cc": "다른 사람 (나는 참조)"}.get(cond.recipient) or lists[cond.list_kind]
    where = ("사외" if cond.external else "사내") + (" · 자동 발송" if cond.auto_sent else "")
    owner = req.owner
    me = " · ".join(x for x in (owner.name, owner.position, owner.team) if x) or "나"
    r = req.received_at
    return (
        f"받은날짜: {r:%Y-%m-%d %H:%M}({WEEKDAYS[r.weekday()]})\n"
        f"나: {me}\n받는사람: {who}\n보낸 곳: {where}\n제목: {req.subject}\n첨부: {', '.join(req.attachments) or '없음'}\n"
        f"본문:\n{trim_body(req.body)}"
    )
